export function queryTelemetryByRegion(regionId?: string) {
  if (!regionId || regionId === 'all-indian-ocean') {
    return {
      regions: REGIONS,
      buoys: OMNI_BUOYS,
    };
  }
  const region = REGIONS.find(
    (r) =>
      r.id === regionId ||
      r.name.toLowerCase().includes(regionId.toLowerCase()) ||
      r.basin.toLowerCase().includes(regionId.toLowerCase())
  );
  const matchedBuoys = OMNI_BUOYS.filter(
    (b) => !region || b.basin === region.basin || region.id === 'all-indian-ocean'
  );
  return {
    region: region ?? REGIONS[0],
    buoys: matchedBuoys,
  };
}

export function queryPfzZones(regionId?: string, targetSpecies?: string, maxDistanceNm?: number) {
  return PFZ_ZONES.filter((z) => {
    const regionMatch =
      !regionId ||
      regionId === 'all-indian-ocean' ||
      z.regionId === regionId ||
      z.regionName.toLowerCase().includes(regionId.toLowerCase()) ||
      z.nearestPort.toLowerCase().includes(regionId.toLowerCase());
    const speciesMatch =
      !targetSpecies ||
      z.species.some((s) => s.toLowerCase().includes(targetSpecies.toLowerCase()));
    const distMatch = !maxDistanceNm || z.distanceNm <= maxDistanceNm;
    return regionMatch && speciesMatch && distMatch;
  });
}

export function queryMarineAlerts(regionId?: string, severityFilter?: string) {
  return MARINE_ALERTS.filter((a) => {
    const regionMatch =
      !regionId ||
      regionId === 'all-indian-ocean' ||
      a.regionId === regionId ||
      a.regionName.toLowerCase().includes(regionId.toLowerCase());
    const sevMatch =
      !severityFilter ||
      severityFilter.toLowerCase() === 'all' ||
      a.severity.toLowerCase() === severityFilter.toLowerCase();
    return regionMatch && sevMatch;
  });
}
